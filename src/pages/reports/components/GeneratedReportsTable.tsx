import React, { useState } from 'react';
import { Card, PillButton } from '../../../components/common';
import type { GeneratedReportItem } from '../../../types/reports';

export interface GeneratedReportsTableProps {
  reports: GeneratedReportItem[];
  onGenerateCustomReport?: () => void;
  onDownloadReport?: (report: GeneratedReportItem) => void;
  className?: string;
}

export const GeneratedReportsTable: React.FC<GeneratedReportsTableProps> = ({
  reports,
  onGenerateCustomReport,
  onDownloadReport,
  className = '',
}) => {
  const [selectedIds, setSelectedIds] = useState<string[]>([]);

  const handleSelectAll = (e: React.ChangeEvent<HTMLInputElement>) => {
    if (e.target.checked) {
      setSelectedIds(reports.map((r) => r.id));
    } else {
      setSelectedIds([]);
    }
  };

  const handleToggleSelect = (id: string) => {
    setSelectedIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  };

  return (
    <Card padding="none" className={`flex flex-col overflow-hidden ${className}`}>
      <div className="p-4 sm:p-5 flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-[#DFECF3]">
        <div className="flex items-center gap-2.5">
          <div className="w-7 h-7 rounded-lg bg-gradient-to-br from-[#002941] to-[#164E6E] text-[#CFE8E1] flex items-center justify-center shadow-xs">
            <span className="material-symbols-outlined text-[16px]">description</span>
          </div>
          <h2 className="text-base sm:text-lg font-bold text-[#002941]">
            Generated Report History
          </h2>
          {selectedIds.length > 0 && (
            <span className="px-2.5 py-0.5 rounded-full text-[11px] font-bold bg-[#002941] text-[#CFE8E1]">
              {selectedIds.length} Selected
            </span>
          )}
        </div>

        <div className="flex items-center gap-2">
          <PillButton
            variant="ghost"
            size="sm"
            icon={<span className="material-symbols-outlined text-[16px]">filter_list</span>}
          >
            Filter
          </PillButton>
          <PillButton
            variant="primary"
            size="sm"
            icon={<span className="material-symbols-outlined text-[16px]">add</span>}
            onClick={onGenerateCustomReport}
          >
            Generate Custom Report
          </PillButton>
        </div>
      </div>

      <div className="overflow-x-auto w-full">
        <table className="w-full text-left text-xs min-w-[640px]">
          <thead className="bg-[#F8FAFA] text-[#566E7F] font-bold uppercase tracking-wider text-[11px] border-b border-[#DFECF3]">
            <tr>
              <th className="py-3 px-4 sm:px-5 w-10">
                <input
                  type="checkbox"
                  aria-label="Select all reports"
                  checked={reports.length > 0 && selectedIds.length === reports.length}
                  onChange={handleSelectAll}
                  className="rounded-[4px] border-[#BDD7E7] text-[#002941] focus:ring-[#002941] cursor-pointer"
                />
              </th>
              <th className="py-3 px-4">Report Name</th>
              <th className="py-3 px-4">Category</th>
              <th className="py-3 px-4">Generated By</th>
              <th className="py-3 px-4">Date</th>
              <th className="py-3 px-4">Format</th>
              <th className="py-3 px-4 sm:px-5 text-right">Action</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-[#DFECF3]">
            {reports.map((r) => {
              const isSelected = selectedIds.includes(r.id);

              return (
                <tr
                  key={r.id}
                  className={`transition-colors ${
                    isSelected ? 'bg-[#F0F5F9]' : 'hover:bg-[#F8FAFA]/80'
                  }`}
                >
                  <td className="py-3.5 px-4 sm:px-5">
                    <input
                      type="checkbox"
                      aria-label={`Select report ${r.reportName}`}
                      checked={isSelected}
                      onChange={() => handleToggleSelect(r.id)}
                      className="rounded-[4px] border-[#BDD7E7] text-[#002941] focus:ring-[#002941] cursor-pointer"
                    />
                  </td>
                  <td className="py-3.5 px-4 font-bold text-[#002941]">
                    {r.reportName}
                  </td>
                  <td className="py-3.5 px-4 text-[#566E7F]">
                    {r.category}
                  </td>
                  <td className="py-3.5 px-4 font-semibold text-[#002941]">
                    {r.generatedBy}
                  </td>
                  <td className="py-3.5 px-4 text-[#566E7F]">
                    {r.date}
                  </td>
                  <td className="py-3.5 px-4">
                    <span
                      className={`px-2 py-0.5 rounded-full text-[10px] font-bold ${
                        r.format === 'PDF'
                          ? 'bg-[#FFF4F3] border border-[#FFD0CC] text-[#FD6E6E]'
                          : 'bg-[#CFE8E1] text-[#103530]'
                      }`}
                    >
                      {r.format}
                    </span>
                  </td>
                  <td className="py-3.5 px-4 sm:px-5 text-right">
                    <button
                      type="button"
                      onClick={() => onDownloadReport && onDownloadReport(r)}
                      className="w-8 h-8 rounded-full flex items-center justify-center text-[#566E7F] hover:text-[#002941] hover:bg-[#EBF1F5] transition-all cursor-pointer ml-auto"
                      title={`Download ${r.format}`}
                    >
                      <span className="material-symbols-outlined text-[18px]">
                        download
                      </span>
                    </button>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </Card>
  );
};
